/** 向きの名前から引く。知らない名前は黙って横型にせず、その場で落とす。 */
export function sceneAspect(name = 'landscape') {
  const found = SCENE_ASPECTS[name];
  if (!found) throw new Error(`向き ${name} は ${Object.keys(SCENE_ASPECTS).join(' / ')} のどれかです`);
  return found;
}

